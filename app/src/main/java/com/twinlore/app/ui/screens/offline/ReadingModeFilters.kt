package com.twinlore.app.ui.screens.offline

import android.net.Uri
import org.json.JSONArray
import org.json.JSONObject

/**
 * Reading-mode chrome strip for offline guide viewers.
 *
 * The offline single-guide + page-group viewers render saved pages exactly
 * as the source site delivered them — header nav, sidebars, related-guide
 * lists, footers, comments, inline rate/share widgets. This module
 * declares one body-keep selector per known host and emits the JS that
 * walks the ancestor chain from that body element up to `<body>`, hiding
 * every sibling at every level. The result is "just the guide".
 *
 * Per-host body-keep whitelist with a hard safety net: if [filterForHost]
 * returns null (unknown host, malformed URL, MHT with no saved URL) OR the
 * declared selector matches nothing on the current page, the script
 * early-returns and the page renders unchanged. We never blank a page.
 *
 * Gated at the call site by the per-vault `guideThemeInject` toggle, the
 * same flag that governs palette CSS injection. Theme on → palette + chrome
 * strip; theme off → page as saved.
 *
 * Selector confidence is anchored to fixtures in
 * `app/src/test/resources/fixtures/reading-mode/`. If a site redesigns the
 * shape we lean on, the matching fixture test fails and points at the
 * entry that needs updating — no silent rot.
 */

/**
 * One host's reading-mode signature.
 *
 * [matches] decides whether [bodySelector] applies to a saved URL. Order
 * in [FILTERS] matters: more specific predicates (e.g. host + path) come
 * before broader same-host fallbacks.
 *
 * [bodySelector] is the CSS selector for the visible guide body. The JS
 * walks up from this element to `<body>`, hiding siblings at every level.
 *
 * [keepAlso] are selectors for chrome that should stay visible even though
 * it's a sibling of (or otherwise outside) the keep chain — typically the
 * site's top header so users keep their navigation bar. Pre-pass: each
 * matched element and every ancestor up to `<body>` is marked keep, so
 * the sibling-hide loop skips them automatically.
 *
 * [removeWithin] are selectors for in-body junk that survives the keep
 * chain (rate-this widgets, comment threads, in-content ads, MediaWiki
 * navboxes, auto-generated tables of contents). Hidden in addition to the
 * keep-chain pass. Elements already on the keep chain are skipped so a
 * removeWithin selector that accidentally matches an ancestor of
 * [bodySelector] (or anything in [keepAlso]) can't blank the page.
 */
data class HostFilter(
    val name: String,
    val matches: (Uri) -> Boolean,
    val bodySelector: String,
    val keepAlso: List<String> = emptyList(),
    val removeWithin: List<String> = emptyList(),
    /**
     * Selectors for chrome we want gone from the visible page but kept in
     * the layout. Each match is pre-marked `data-gametwin-keep="1"` so the
     * sibling-hide loop + removeWithin pass leave it alone, then a final
     * pass sets `style.visibility = "hidden"` and tags
     * `data-gametwin-spaced="1"`. The element renders blank but occupies
     * its natural height — the body below doesn't jump.
     *
     * When the element is `position: fixed` (a sticky site header that
     * overlays content), `visibility: hidden` alone produces a zero-height
     * blank because fixed boxes don't reserve flow space. The JS detects
     * that case via `getComputedStyle().position` and inserts an empty
     * `<div data-gametwin-spacer="1">` sibling whose height matches the
     * element's `getBoundingClientRect().height`. `REMOVE_READING_MODE_JS`
     * removes spacers along with everything else.
     *
     * Use when the user wants empty space rather than a tight strip. For
     * "gone, take the space with you" use sibling-hide via plain
     * non-membership in [keepAlso].
     */
    val hideButReserveSpace: List<String> = emptyList(),
    /**
     * When non-blank, the reading-mode JS finds the element with this
     * `id` attribute, walks up to the closest heading (`h1`–`h6`), hides
     * the heading, hides the heading's next sibling if it's a `<ul>`,
     * then hides trailing siblings whose text content is whitespace-only.
     *
     * Anchor-based instead of position-based because OmegaMetroid chapter
     * pages can be `<h2>banner-image</h2><h2 id="walkthrough">Walkthrough</h2>
     * <ul>chapter list</ul>` (Super Metroid) OR `<h3 id="walkthrough">
     * Walkthrough</h3><ul>…</ul><p>&nbsp;</p>` (Zero Mission). The
     * `id="walkthrough"` anchor is generated by WordPress's
     * Auto-Anchor-Links plugin from the heading slug, so it stays put
     * across both shapes and never matches the chapter banner.
     */
    val stripPreambleAnchorId: String = "",
    /**
     * JS snippet executed at the head of [buildReadingModeJs]'s IIFE,
     * before the keep-chain / sibling-hide / removeWithin passes. Use for
     * host-specific DOM transforms that change what the subsequent passes
     * see — e.g. rewriting form-submit image inputs to anchor-wrapped
     * images so long-press host discrimination can route them as links.
     *
     * Idempotent: runs every time reader-mode is re-applied. Tag rewritten
     * elements with a `data-gametwin-rewrite=<kind>` attribute and gate
     * the rewrite block on its absence so a second invocation is a no-op.
     *
     * Blank (default) means no pre-transform.
     *
     * End with a semicolon and avoid `//` line comments — the IIFE is a
     * single line, so a line comment would swallow the rest of the
     * script. Malformed snippets are caught by the outer try/catch and
     * silently no-op the entire reader-mode pass for the host.
     */
    val preTransformsJs: String = "",
)

/**
 * Resolve [savedUrl] to a host filter, or null when no entry matches.
 *
 * Null URLs (legacy saves missing a recorded source URL) and malformed
 * URLs both return null — the safe-fallback path where the prelude and
 * theme-toggle JS are no-ops and the page renders unchanged.
 */
fun filterForHost(savedUrl: String?): HostFilter? {
    if (savedUrl.isNullOrBlank()) return null
    val uri = try {
        Uri.parse(savedUrl)
    } catch (e: Exception) {
        return null
    }
    if (uri.host.isNullOrBlank()) return null
    return FILTERS.firstOrNull { it.matches(uri) }
}

/**
 * JS payload (IIFE) that applies [filter] to the current document.
 *
 * Idempotent: a second invocation against an already-stripped DOM is a
 * no-op via the `data-gametwin-keep` / `data-gametwin-hidden` guards.
 * Symmetric with [REMOVE_READING_MODE_JS] — what this hides, that unwinds.
 *
 * Safe-fallback: returns at the first line if the body selector matches
 * nothing on this document. Caller can fire-and-forget; no error path.
 *
 * Bottom scroll padding: a 4em `#gt-botpad` spacer is appended to the kept
 * body element (`bodySelector`), NOT to `document.body`. On SPA layouts that
 * pin the root chain to the viewport (IGN's Next.js sets
 * `html, body, #root, #__next { height: 100% }`), a `document.body`-appended
 * div can't extend the scroll area — body is height-clamped, so the spacer
 * has nowhere to grow. The kept body element is the content that actually
 * overflows and drives scrolling, so a spacer inside it adds real scroll
 * length on every layout (and is equivalent for traditional auto-height
 * pages). [SCROLL_PAD_JS] still handles top padding + non-reader-mode pages.
 *
 * Mirrors the single-line IIFE shape used by `buildPaletteCssJs`.
 */
fun buildReadingModeJs(filter: HostFilter): String {
    val sel = JSONObject.quote(filter.bodySelector)
    val keepJson = JSONArray(filter.keepAlso).toString()
    val hbsJson = JSONArray(filter.hideButReserveSpace).toString()
    val removeJson = JSONArray(filter.removeWithin).toString()
    val anchorId = JSONObject.quote(filter.stripPreambleAnchorId)
    val pre = filter.preTransformsJs
    return """(function(){try{$pre var sel=$sel;var ka=$keepJson;var hbs=$hbsJson;var rm=$removeJson;var ai=$anchorId;var n=document.querySelector(sel);if(!n)return;if(!document.getElementById("gt-botpad")){var _bp=document.createElement("div");_bp.id="gt-botpad";_bp.dataset.gametwinSpacer="1";_bp.dataset.gametwinKeep="1";_bp.style.height="4em";n.appendChild(_bp);}function markKeepChain(el){while(el&&el!==document.body){el.dataset.gametwinKeep="1";el=el.parentNode;}}for(var i=0;i<ka.length;i++){var elsK=document.querySelectorAll(ka[i]);for(var j=0;j<elsK.length;j++){markKeepChain(elsK[j]);}}for(var i=0;i<hbs.length;i++){var elsH=document.querySelectorAll(hbs[i]);for(var j=0;j<elsH.length;j++){markKeepChain(elsH[j]);}}while(n&&n!==document.body){var p=n.parentNode;if(!p)break;for(var i=0;i<p.children.length;i++){var c=p.children[i];if(c!==n&&c.dataset.gametwinKeep!=="1"&&c.dataset.gametwinHidden!=="1"){c.dataset.gametwinHidden="1";c.style.setProperty("display","none","important");}}n.dataset.gametwinKeep="1";n=p;}for(var i=0;i<rm.length;i++){var els=document.querySelectorAll(rm[i]);for(var j=0;j<els.length;j++){var e=els[j];if(e.dataset.gametwinKeep==="1")continue;if(e.dataset.gametwinHidden!=="1"){e.dataset.gametwinHidden="1";e.style.setProperty("display","none","important");}}}for(var i=0;i<hbs.length;i++){var elsS=document.querySelectorAll(hbs[i]);for(var j=0;j<elsS.length;j++){var s=elsS[j];if(s.dataset.gametwinSpaced==="1")continue;s.dataset.gametwinSpaced="1";try{var cs=window.getComputedStyle(s);if(cs&&cs.position==="fixed"){var h=s.getBoundingClientRect().height;if(h>0&&s.parentNode){var sp=document.createElement("div");sp.dataset.gametwinSpacer="1";sp.style.height=h+"px";s.parentNode.insertBefore(sp,s.nextSibling);}}}catch(e){}s.style.setProperty("visibility","hidden","important");}}if(ai){var anc=document.getElementById(ai);if(anc){var h=anc.closest("h1,h2,h3,h4,h5,h6");if(h){h.dataset.gametwinHidden="1";h.style.setProperty("display","none","important");var nx=h.nextElementSibling;if(nx&&nx.tagName==="UL"){nx.dataset.gametwinHidden="1";nx.style.setProperty("display","none","important");var sib=nx.nextElementSibling;while(sib){var tt=(sib.textContent||"").replace(/\s/g,"");if(tt.length===0){sib.dataset.gametwinHidden="1";sib.style.setProperty("display","none","important");sib=sib.nextElementSibling;}else break;}}}}}}catch(e){}})();"""
}

/**
 * JS payload (IIFE) that undoes [buildReadingModeJs] on the current
 * document — clears the inline `display:none` overrides this module set
 * and removes the `data-gametwin-*` markers.
 *
 * Symmetric with [buildReadingModeJs] (host-agnostic; finds work by
 * attribute, not selector). Safe to call when nothing is hidden.
 */
const val REMOVE_READING_MODE_JS: String =
    """(function(){try{var h=document.querySelectorAll('[data-gametwin-hidden="1"]');for(var i=0;i<h.length;i++){h[i].style.removeProperty("display");h[i].removeAttribute("data-gametwin-hidden");}var k=document.querySelectorAll('[data-gametwin-keep="1"]');for(var i=0;i<k.length;i++){k[i].removeAttribute("data-gametwin-keep");}var sp=document.querySelectorAll('[data-gametwin-spaced="1"]');for(var i=0;i<sp.length;i++){sp[i].style.removeProperty("visibility");sp[i].removeAttribute("data-gametwin-spaced");}var spc=document.querySelectorAll('[data-gametwin-spacer="1"]');for(var i=0;i<spc.length;i++){if(spc[i].parentNode)spc[i].parentNode.removeChild(spc[i]);}}catch(e){}})();"""

/**
 * `<script>` block wrapping [buildReadingModeJs] for HTML splice at
 * prelude time. Spliced just before `</body>` so it executes during DOM
 * parse and the first paint is already stripped — no flash of full chrome.
 *
 * Mirrors the style of `spliceInlineDecorationsScript` in this package.
 */
fun buildReadingModeInjection(filter: HostFilter): String =
    "<script id=\"gt-reading-mode\">${buildReadingModeJs(filter)}</script>"

/**
 * Idempotently adds top + bottom scroll padding so the first lines aren't glued
 * to the top edge (~3 lines of breathing room) and the last lines clear the
 * bottom edge. Exposed standalone so the page-group viewer can give EVERY page
 * the padding, reader mode or not.
 *
 * Sets `padding-top` / `padding-bottom` on the document's scrolling element
 * (the real scroll root — `<html>` in standards mode, falling back to `<body>`)
 * rather than appending spacer `<div>`s. Root padding is robust across
 * SPA-style layouts (e.g. IGN's Next.js DOM, where a body-appended div may not
 * extend the scroll area) and can't be hidden by a reader-mode keep-chain or
 * stripped by [REMOVE_READING_MODE_JS], so it persists across the reader toggle.
 */
const val SCROLL_PAD_JS: String =
    """(function(){try{var se=document.scrollingElement||document.documentElement||document.body;if(se){se.style.setProperty("padding-top","4em","important");se.style.setProperty("padding-bottom","4em","important");}}catch(e){}})();"""

// -----------------------------------------------------------------------
// Host registry
//
// Entries pinned against fixtures in
// `app/src/test/resources/fixtures/reading-mode/`. Reading the body shape
// each fixture exhibited, not guessing.
//
// Order matters when two predicates share a host (Zelda Dungeon wiki vs
// blog): more specific gates come first.
// -----------------------------------------------------------------------

private val FILTERS: List<HostFilter> = listOf(

    // GameFAQs (gamefaqs.gamespot.com)
    //   - HTML FAQ format: `<div id="faqwrap">` containing `.ftoc` + `.faqtext`
    //   - Text FAQ format: `<div id="faqwrap">` containing `<pre id="faqtext">`
    // Both formats share the same outer wrapper, so one entry covers both.
    // Saves from index pages (.../faqs/) lack #faqwrap — script early-returns.
    HostFilter(
        name = "gamefaqs",
        matches = { uri ->
            val h = uri.host ?: ""
            h == "gamefaqs.gamespot.com" || h.endsWith(".gamefaqs.gamespot.com") ||
                h == "gamefaqs.com" || h.endsWith(".gamefaqs.com")
        },
        bodySelector = "#faqwrap",
        // Two sibling-above blocks of #faqwrap that the keep-chain would
        // otherwise hide:
        //
        //   `.body.ffaq > h2.title` — guide-info block carrying the
        //   "Guide and Walkthrough by <author>" line and the PayPal
        //   Donate button. Present in both single-page and paginated
        //   FAQs.
        //
        //   `ul.paginate` — Previous / ToC / Next chapter chevrons on
        //   paginated HTML FAQs. There are two on the page (above AND
        //   below #faqwrap) and the keepAlso pre-pass marks both since
        //   the selector matches every occurrence. Single-page FAQs
        //   don't carry this class, so the selector is a clean no-op
        //   on those.
        keepAlso = listOf(".body.ffaq > h2.title", "ul.paginate"),
        // #contrib_rec: "Recommend this Guide?" overlay (also hit by
        // CosmeticFilters in the live browser; double-hidden offline).
        //
        // `ul.paginate a:not([href])`: the "Table of Contents" item in the
        // Prev / ToC / Next bar. In a page-group each page IS one chapter, so
        // the in-page ToC button is redundant (and its panel doesn't carry
        // across the offline split). Prev and Next carry real hrefs, so they
        // stay — only the hrefless ToC anchor is hidden. Kept out of `:has`
        // territory so an unsupported selector can't throw and abort the strip.
        removeWithin = listOf("#contrib_rec", "ul.paginate a:not([href])"),
        // The PayPal donate button is delivered as
        // `<form class="tipjar_form" action="paypal.com…">
        //    <input type="image" src="paypal_donate.gif">
        //  </form>`
        // — no anchor wrapping. WebView.HitTestResult reports plain
        // IMAGE_TYPE for long-press, so the offline viewer's image
        // action dialog (Open in viewer / Save / Copy URL) surfaces
        // for what is really a payment link. Rewrite the form to
        // `<a href=action target=_blank rel=noopener noreferrer>
        //    <img src=input.src alt= title=>
        //  </a>` so:
        //   - tap follows the anchor (WebView's normal click handling
        //     opens PayPal in the browser tab),
        //   - long-press reports SRC_IMAGE_ANCHOR_TYPE with extra =
        //     PayPal URL — the isExternalAnchor check then
        //     routes to the link dialog (single-guide) or no-op
        //     (page-group, per its existing no-link-long-press design).
        //
        // Idempotent via the `data-gametwin-rewrite="tipjar"` marker:
        // a second invocation against an already-rewritten anchor is
        // a no-op.
        preTransformsJs = """
            var forms = document.querySelectorAll('form.tipjar_form');
            for (var i = 0; i < forms.length; i++) {
              var f = forms[i];
              if (f.dataset.gametwinRewrite === 'tipjar') continue;
              var input = f.querySelector('input[type="image"]');
              if (!input) continue;
              var a = document.createElement('a');
              a.href = f.action;
              a.target = '_blank';
              a.rel = 'noopener noreferrer';
              a.dataset.gametwinRewrite = 'tipjar';
              var img = document.createElement('img');
              img.src = input.src;
              img.alt = input.alt || '';
              img.title = input.title || '';
              a.appendChild(img);
              if (f.parentNode) f.parentNode.replaceChild(a, f);
            }
        """,
    ),

    // Neoseeker. Two page formats share the same host:
    //
    //   `/<game>/walkthrough`               — `#walkthrough_page_wrapper`
    //   `/<game>/faqs/<id>-p.html`          — `#markupfaq`
    //
    // The FAQ format wraps the body in `#markupfaq` inside
    // `#maincontent` inside `#container`; the keep-chain walks up
    // from `#markupfaq`, killing `header#entireheader` as a sibling
    // of `#maincontent`. The comma-list selector hits whichever
    // wrapper is present (matches the OmegaMetroid desktop-vs-WPtouch
    // pattern).
    //
    // Site top bar `<header id="entireheader">` is intentionally NOT
    // kept — its inner row (Forums / Find Forums / forum-search form)
    // is irrelevant inside an offline saved guide, and the brand band
    // isn't worth the visual noise either. The sibling-hide pass
    // display:none's it like any other top-level chrome sibling.
    //
    // `#product-hub-nav` is the FAQ page's in-content navbar
    // (Cheats / FAQs / Forum / Media / Reviews / Wiki). It lives
    // INSIDE `#markupfaq` so the keep-chain leaves it visible —
    // removeWithin nukes it. Walkthrough pages don't carry this id,
    // so the selector is a clean no-op there.
    HostFilter(
        name = "neoseeker",
        matches = { uri ->
            val h = uri.host ?: ""
            h == "neoseeker.com" || h.endsWith(".neoseeker.com")
        },
        bodySelector = "#walkthrough_page_wrapper, #markupfaq",
        keepAlso = emptyList(),
        removeWithin = listOf(".social_share", "#product-hub-nav"),
    ),

    // OmegaMetroid chapter sub-pages (e.g. /metroid-zero-mission-walkthrough/
    // return-to-zebes/). Path = `/<game>-walkthrough/<chapter>/` — two
    // segments where the first ends with `-walkthrough`. The first h3 +
    // first <ul> inside `.post-content` are a verbatim repeat of the
    // hub's chapter nav, and the bottom carries a `colorbox` link bar
    // (Walkthrough | 100% Map | …). Both are removed here. Must come
    // BEFORE the hub entry — the hub matcher is broader.
    HostFilter(
        name = "omegametroid-chapter",
        matches = { uri ->
            val h = uri.host ?: ""
            val segs = uri.path.orEmpty().trim('/').split('/').filter { it.isNotEmpty() }
            (h == "omegametroid.com" || h.endsWith(".omegametroid.com")) &&
                segs.size >= 2 && segs[0].endsWith("-walkthrough")
        },
        // Desktop theme wraps the post in `<article>` inside `.main-content
        // > .main-container`. The mobile (WPtouch) theme wraps it in
        // `<div class="post section post-NNN">` inside `.content-wrap >
        // #content`. The comma-list selector matches whichever is
        // present so saves made with either user-agent get the same
        // chrome strip.
        bodySelector = ".main-content article, .post.section",
        removeWithin = listOf(
            "[id^=\"colorbox_main_container\"]",
        ),
        // The preamble is anchor-based. WordPress's Auto-Anchor-Links
        // plugin gives the "Walkthrough" heading `id="walkthrough"`
        // regardless of heading level. The JS walks from that anchor to
        // its closest heading, hides it, hides the next `<ul>` (chapter
        // list), and sweeps trailing whitespace-only siblings (the
        // `<p>&nbsp;</p>` spacer on Zero Mission, the empty `<h4>&nbsp;</h4>`
        // on Super Metroid). The chapter banner — which lives in a
        // SEPARATE earlier heading without `#walkthrough` — stays
        // visible because the anchor never points at it.
        stripPreambleAnchorId = "walkthrough",
    ),

    // OmegaMetroid (WordPress) — chain on the desktop theme:
    //   #page-wrap > .page-content > .main-content > .main-container
    //     > article.post.page (id varies per post)
    // Mobile (WPtouch) theme wraps the post in
    //   .page-wrapper > .content-wrap > #content > .post.section
    // The comma-list bodySelector accepts whichever wrapper is present
    // — same approach as omegametroid-chapter above. Hub pages need no
    // removeWithin because the chapter list IS the content.
    HostFilter(
        name = "omegametroid",
        matches = { uri ->
            val h = uri.host ?: ""
            h == "omegametroid.com" || h.endsWith(".omegametroid.com")
        },
        bodySelector = ".main-content article, .post.section",
    ),

    // Bulbapedia (MediaWiki) — chain:
    //   .bv-content-wrapper > .bv-content-wrapper__content-area
    //     > main#content.mw-body > #bodyContent > #mw-content-text
    //
    // MediaWiki article chrome that lives INSIDE #mw-content-text and
    // needs an extra hide pass: `.printfooter` ("Retrieved from…" line),
    // `.catlinks` (category-link strip at the article foot). Verified
    // against the Browse:Walkthroughs fixture; article-page-specific
    // selectors (.navbox, .editsection) are not in this fixture and
    // weren't added speculatively — capture an article fixture to pin
    // those before declaring them.
    //
    // `header.bv-header` (site nav: logo + search + News / Forums /
    // Socials / More / Editors / Account) is in `hideButReserveSpace`:
    // it's invisible inside saved guides but keeps its layout slot so
    // the body below doesn't jump. If Bulbapedia ships the header as
    // `position: fixed` the JS auto-inserts a height-matching spacer
    // sibling — verify on-device.
    HostFilter(
        name = "bulbapedia",
        matches = { uri ->
            val h = uri.host ?: ""
            h == "bulbagarden.net" || h.endsWith(".bulbagarden.net")
        },
        bodySelector = "#mw-content-text",
        // `#firstHeading` is the MediaWiki article title (e.g.
        // "Walkthrough:Pokémon Emerald/Part 6"). It lives in
        // `header.content__header` on Bulbapedia — sibling of
        // `#mw-content-text` inside `#bodyContent` — so the keep-chain
        // would otherwise hide it. Marking the h1 walks up to the
        // wrapper and keeps the whole title block visible.
        keepAlso = listOf("#firstHeading"),
        hideButReserveSpace = listOf("header.bv-header"),
        removeWithin = listOf(".printfooter", ".catlinks"),
    ),

    // Zelda Dungeon wiki (MediaWiki) — same shape as Bulbapedia. The
    // host-prefix match on zeldadungeon.net is shared with the blog
    // entry below; the path-prefix gate here keeps wiki articles separate.
    // Verified against the A Link to the Past article: `.navbox` (lateral
    // nav cluster), `.printfooter`, `.catlinks`, `.siteSub` ("From Zelda
    // Dungeon" subtitle), `#toc` (auto-generated table-of-contents at the
    // top of every article).
    HostFilter(
        name = "zeldadungeon-wiki",
        matches = { uri ->
            val h = uri.host ?: ""
            val p = uri.path.orEmpty()
            (h == "zeldadungeon.net" || h.endsWith(".zeldadungeon.net")) &&
                p.startsWith("/wiki/")
        },
        bodySelector = "#mw-content-text",
        // `#firstHeading` is the article title; kept for parity with the
        // bulbapedia entry — same MediaWiki ID across skins.
        keepAlso = listOf("#firstHeading"),
        removeWithin = listOf("#toc", ".navbox", ".printfooter", ".catlinks", ".siteSub"),
    ),

    // Zelda Dungeon blog (WordPress-ish). Walkthrough hub pages wrap their
    // body in `<div class="content page-content">`. Other zeldadungeon.net
    // pages without that class fall through to the safe no-match path.
    // Must come AFTER zeldadungeon-wiki — both share the same host gate.
    //
    // Chapter sub-pages (e.g. /a-link-to-the-past-walkthrough/eastern-palace/)
    // wrap their body in `<div class="walkthrough wt2">`. The FIRST and
    // ONLY direct `<ul>` child of that wrapper is the full chapter-list
    // (Chapter 1 → Chapter 13) appearing before the first section heading
    // — that's the part to hide. The wrapper itself carries the body
    // content (sections, paragraphs, images) so it must STAY. Targeting
    // the direct `<ul>` keeps the body intact.
    //
    // Top site chrome + in-content cleanup. The three top-chrome IDs
    // (#mobilenav, #header, #sitenav) are body-direct siblings of `#wrapper`
    // (where `.page-content` lives). The keep-chain sibling-hide pass should
    // hit them, but explicit removeWithin entries are robust against layout
    // drift and Bootstrap-affix-style dynamic positioning. `.news-readmore`
    // and `#disqus_thread` are siblings of `.page-content` inside
    // `.content-wrap` — the keep-chain already hides them as siblings of the
    // keep selector, but listing them in removeWithin explicitly nukes them
    // even if a future site change moves them inside `.page-content`.
