                uri.path.orEmpty().contains("/wiki/")
        },
        bodySelector = "#wiki-body",
        keepAlso = listOf("h1.gh-header-title"),
        removeWithin = listOf(".gh-header-actions", ".gh-header-meta", "#wiki-footer"),
        // The offline viewer lays a saved GitHub page out at a ~1234px layout
        // viewport (its desktop intrinsic width), then scales it down to the
        // phone screen. At >=768px GitHub's Primer `.Layout` is in its desktop
        // TWO-COLUMN mode, so `#wiki-body` is squeezed to the ~28%-wide main
        // column and the text renders tiny in a narrow strip with a big empty
        // gutter — exactly what we don't want.
        //
        // Fix in two reinforcing moves, host-scoped to the wiki subtree:
        //
        //  1. Force the viewport meta to `width=device-width` so the page lays
        //     out at the phone width. Below Primer's `md` breakpoint the
        //     `Layout--flowRow-until-md` Layout collapses to a single full-width
        //     column on its own and the text renders at normal size.
        //  2. Belt-and-suspenders for the case where the WebView doesn't reflow
        //     the layout viewport from a runtime meta change: collapse the
        //     `.Layout` grid to a block, uncap `#wiki-wrapper` (Primer's
        //     `container-xl` caps at 1280px), and full-width `.Layout-main`, so
        //     the content's intrinsic min-width drops toward device-width.
        //     Wrap `<pre>` blocks (code/ASCII) so a wide one can't re-inflate
        //     the min-width and force horizontal scroll.
        //
        // Runs before the strip (which doesn't care about display). Idempotent.
        preTransformsJs = """
            var gtvp = document.querySelector('meta[name="viewport"]');
            if (!gtvp) { gtvp = document.createElement('meta'); gtvp.setAttribute('name', 'viewport'); if (document.head) document.head.appendChild(gtvp); }
            gtvp.setAttribute('content', 'width=device-width, initial-scale=1');
            var gtlay = document.querySelector('#wiki-content .Layout');
            if (gtlay) { gtlay.style.setProperty('display', 'block', 'important'); }
            var gtwrap = document.querySelector('#wiki-wrapper');
            if (gtwrap) { gtwrap.style.setProperty('max-width', '100%', 'important'); }
            var gtmain = document.querySelector('#wiki-content .Layout-main');
            if (gtmain) { gtmain.style.setProperty('width', '100%', 'important'); gtmain.style.setProperty('max-width', '100%', 'important'); }
            var gtpre = document.querySelectorAll('#wiki-body pre');
            for (var gti = 0; gti < gtpre.length; gti++) { gtpre[gti].style.setProperty('white-space', 'pre-wrap', 'important'); gtpre[gti].style.setProperty('overflow-wrap', 'break-word', 'important'); }
        """,
    ),

