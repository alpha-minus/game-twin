package com.twinlore.app.data

import android.content.Context
import android.util.Log
import com.twinlore.app.data.library.PageGroupTextIndex
import com.twinlore.app.data.local.PageGroupEntryEntity
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import javax.inject.Inject
import javax.inject.Singleton

/**
 * Per-group find-sidecar cache. Mirrors [MhtCacheManager]:
 *   `<cacheDir>/page_group_sidecars/<groupTabId>/<resourceId>.txt`
 *   `<cacheDir>/page_group_sidecars/<groupTabId>/.sidecar_cache` (LRU marker)
 *
 * Sidecars are written by [com.twinlore.app.data.library.PageGroupSaveCoordinator]
 * right after each MHT is staged, and regenerated by [ensureForGroup] when the
 * viewer opens a group whose cache has been evicted or never existed (e.g. a
 * group restored from a library snapshot on a different device). Sidecars are
 * NOT stored in the library folder — they're internal derived data that can
 * always be rebuilt from the MHT.
 */
@Singleton
class PageGroupSidecarCache @Inject constructor(
    @ApplicationContext private val context: Context,
    private val mhtParser: MhtParser
) {
    companion object {
        private const val TAG = "PageGroupSidecarCache"
        private const val MAX_CACHED_GROUPS = 20
        private const val CACHE_MARKER_FILE = ".sidecar_cache"
        private const val ROOT_DIR = "page_group_sidecars"
        private const val PARSE_SCRATCH_DIR = "page_group_render"
    }

    private val root: File get() = File(context.cacheDir, ROOT_DIR)

    /** Per-group cache directory; created if absent. */
    fun groupDir(groupTabId: String): File =
        File(root, groupTabId).apply { mkdirs() }

    /** Sidecar file path for the given resource. Caller must check `exists()`. */
    fun sidecarFile(groupTabId: String, mhtResourceId: String): File =
        File(groupDir(groupTabId), "$mhtResourceId.txt")

    /** Persist a sidecar body (called by the save coordinator). Stamps the LRU marker. */
    fun writeSidecar(groupTabId: String, mhtResourceId: String, body: String) {
        val dir = groupDir(groupTabId)
        File(dir, "$mhtResourceId.txt").writeText(body)
        File(dir, CACHE_MARKER_FILE).writeText(System.currentTimeMillis().toString())
    }

    /** Touch the LRU marker on viewer open / find use. */
    fun touch(groupTabId: String) {
        val marker = File(groupDir(groupTabId), CACHE_MARKER_FILE)
        marker.writeText(System.currentTimeMillis().toString())
    }

    /** Remove the entire per-group cache dir. Called by repository.deleteGroup. */
    fun clear(groupTabId: String) {
        File(root, groupTabId).deleteRecursively()
    }

    /** Remove one resource's sidecar (called on last-reference entry removal). */
    fun deleteResource(groupTabId: String, mhtResourceId: String) {
        File(groupDir(groupTabId), "$mhtResourceId.txt").delete()
    }

    /**
     * For each distinct `mht_resource_id` in [entries] that has no cached
     * sidecar on disk, re-derive it: resolve the MHT via [mhtFileResolver],
     * parse with [MhtParser], strip with [PageGroupTextIndex]. Updates the
     * LRU marker on completion. Silently skips resources that fail to resolve
     * or parse so a single bad page doesn't block search for the rest.
     */
    suspend fun ensureForGroup(
        groupTabId: String,
        entries: List<PageGroupEntryEntity>,
        mhtFileResolver: suspend (mhtResourceId: String) -> File?
    ): Unit = withContext(Dispatchers.IO) {
        val byResource = entries.filter { it.mhtResourceId != null }.groupBy { it.mhtResourceId!! }
        if (byResource.isEmpty()) return@withContext
        val dir = groupDir(groupTabId)
        val cacheRootPath = context.cacheDir.absolutePath
        for ((resourceId, rows) in byResource) {
            val target = File(dir, "$resourceId.txt")
            if (target.exists() && target.length() > 0L) continue
            val mht = mhtFileResolver(resourceId) ?: continue
            val parseDir = File(context.cacheDir, "$PARSE_SCRATCH_DIR/$groupTabId/$resourceId")
                .apply { mkdirs() }
            try {
                val parsed = runCatching { mhtParser.parse(mht, parseDir) }.getOrNull() ?: continue
                val referenced = rows.mapNotNull { it.fragment?.removePrefix("#") }.toSet()
                val body = PageGroupTextIndex.buildSidecar(parsed.html, referenced)
                target.writeText(body)
                Log.d(TAG, "regenerated sidecar groupTabId=$groupTabId resourceId=$resourceId bytes=${body.length}")
            } finally {
                // We created parseDir; delete its full MHT extraction (the
                // image bytes were never used — only parsed.html was). On the
                // miss path (continue above), the dir is empty anyway.
                runCatching { parseDir.deleteRecursively() }
                // The resolver's contract: it MAY return a temp file under
                // context.cacheDir (the SAF copy at mht_source/sidecar_<id>.mht).
                // Real file:// library MHTs are NOT in cacheDir and must not be
                // deleted. Use absolute-path-prefix to discriminate.
                if (mht.absolutePath.startsWith(cacheRootPath)) {
                    runCatching { mht.delete() }
                }
            }
        }
        File(dir, CACHE_MARKER_FILE).writeText(System.currentTimeMillis().toString())
    }

    /** List of per-group cache dirs currently on disk (LRU input). */
    fun allGroupDirs(): List<File> =
        root.listFiles()?.filter { it.isDirectory }.orEmpty()

    /** LRU eviction. Keeps the [MAX_CACHED_GROUPS] most-recently-touched groups. */
    fun evictOldEntries(allDirs: List<File> = allGroupDirs()) {
        val cached = allDirs.mapNotNull { dir ->
            val marker = File(dir, CACHE_MARKER_FILE)
            if (marker.exists()) dir to (marker.readText().trim().toLongOrNull() ?: 0L) else null
        }.sortedByDescending { it.second }
        if (cached.size <= MAX_CACHED_GROUPS) return
        val toEvict = cached.drop(MAX_CACHED_GROUPS)
        for ((dir, _) in toEvict) {
            Log.d(TAG, "Evicting page-group sidecar cache: ${dir.name}")
            dir.deleteRecursively()
        }
        Log.d(TAG, "Evicted ${toEvict.size} sidecar cache entries, kept $MAX_CACHED_GROUPS")
    }
}
