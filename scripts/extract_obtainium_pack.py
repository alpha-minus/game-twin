#!/usr/bin/env python3
"""
Extract the Obtainium Emulation Pack catalog from the upstream table.md and
emit Kotlin `RecommendedApp(...)` literals on stdout, one per line, ready to
be diffed into app/src/main/java/com/twinlore/app/data/catalog/RecommendedAppsCatalog.kt.

Usage:
    python3 scripts/extract_obtainium_pack.py > /tmp/catalog.kt

After running, manually:
 1. Diff /tmp/catalog.kt against the current `apps = listOf(...)` block.
 2. For any new Category.Emulator entries, replace the source `about` text with
    console-focused phrasing (e.g. "PlayStation 3", "GameCube + Wii", "Many
    systems (libretro frontend)", "Windows / PC apps").
 3. PC Emulation source rows are emitted with Category.Emulator (PC Emulation
    is merged into the Emulator tab per the design).
 4. Update the `Last updated:` date in the file's header KDoc.

This script is NOT invoked from Gradle; it's a developer tool.
"""

from __future__ import annotations

import json
import re
import sys
import urllib.parse
import urllib.request

SOURCE_URL = "https://raw.githubusercontent.com/RJNY/Obtainium-Emulation-Pack/main/pages/table.md"

# Section header -> Category enum value.
# "PC Emulation" is folded into Emulator per the merged-tab design.
CATEGORY_MAP = {
    "Emulator": "Emulator",
    "Frontend": "Frontend",
    "PC Emulation": "Emulator",
    "Streaming": "Streaming",
    "Track Only": "TrackOnly",
    "Utilities": "Utility",
}

ROW_RE = re.compile(
    r'^\|\s*<a href="(?P<source>[^"]+)">(?P<name>[^<]+)</a>\s*\|\s*'
    r'<a href="[^"]*?r=(?P<obtainium>obtainium://app/[^"]+)">[^<]+</a>\s*\|\s*'
    r'(?P<standard>[^|]+?)\s*\|\s*(?P<dual>[^|]+?)\s*\|\s*$'
)

def fetch_table() -> str:
    with urllib.request.urlopen(SOURCE_URL) as resp:
        return resp.read().decode("utf-8")

def decode_obtainium_id(obtainium_url: str) -> str:
    """The Obtainium URL is obtainium://app/<percent-encoded JSON>. Extract `id`."""
    payload = obtainium_url[len("obtainium://app/"):]
    decoded = urllib.parse.unquote(payload)
    return json.loads(decoded).get("id", "")

def kotlin_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")

def main() -> int:
    text = fetch_table()
    current_category: str | None = None
    out_lines: list[str] = []

    for line in text.splitlines():
        if line.startswith("### "):
            heading = line[4:].strip()
            current_category = CATEGORY_MAP.get(heading)
            if current_category is None:
                print(f"# WARN: unknown category heading: {heading!r}", file=sys.stderr)
            else:
                out_lines.append(f"\n        // --- {heading} ---")
            continue

        if current_category is None:
            continue

        m = ROW_RE.match(line)
        if not m:
            continue

        source_url = m.group("source").strip()
        name = m.group("name").strip()
        obtainium_url = m.group("obtainium").strip()
        try:
            pkg_id = decode_obtainium_id(obtainium_url)
        except Exception as e:
            print(f"# WARN: cannot decode id for {name!r}: {e}", file=sys.stderr)
            continue

        standard = "✅" in m.group("standard")
        dual = "✅" in m.group("dual")

        out_lines.append(
            f'        RecommendedApp(id="{kotlin_escape(pkg_id)}", '
            f'name="{kotlin_escape(name)}", '
            f'category=Category.{current_category}, '
            f'sourceUrl="{kotlin_escape(source_url)}", '
            f'obtainiumUrl="{kotlin_escape(obtainium_url)}", '
            f'standard={str(standard).lower()}, '
            f'dualScreen={str(dual).lower()}, '
            f'about=""),'
        )

    print("// Generated by scripts/extract_obtainium_pack.py - diff & hand-edit `about` fields.")
    print("listOf(")
    for line in out_lines:
        print(line)
    print("    )")
    return 0

if __name__ == "__main__":
    sys.exit(main())
