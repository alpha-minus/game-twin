#!/bin/bash
# Generates adaptive-icon background art + emblem medallions from the source
# icon renders. Requires macOS `sips`. Re-runnable.
set -euo pipefail

SRC="${1:-$HOME/Downloads/New Folder With Items}"
RES="app/src/main/res"
DRAW="$RES/drawable-nodpi"
mkdir -p "$DRAW"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# name  sourcefile  bgHex(no #)  framed(1)|padded(0)
# bg = each icon's TRUE corner colour so the padded square blends into the
# splash background (which uses the same value) — no visible box behind the logo.
ROWS=(
  "pixel|pixel.jpg|360966|1"
  "gold|gold.jpg|12051D|1"
  "cyber|cyber.jpg|060721|1"
  "demonic|demonic.jpg|080708|1"
  "adventure|adventure.jpg|0B0217|1"
  "noire|noire.jpg|060606|1"
)

for row in "${ROWS[@]}"; do
  IFS='|' read -r name src bg framed <<< "$row"
  in="$SRC/$src"
  echo "== $name ($in) =="

  # Normalize to a common 1498x704 canvas (cyber is 2x).
  sips -z 704 1498 "$in" --out "$TMP/${name}_norm.png" >/dev/null

  if [ "$framed" = "1" ]; then
    # Center square = full height, centered horizontally (captures the framed icon).
    sips -c 704 704 "$TMP/${name}_norm.png" --out "$TMP/${name}_sq.png" >/dev/null
  else
    # Frameless (adventure): tighten to the wreath's bounding box (trim side
    # margins), then pad to a square with the flat background color. Padding the
    # full 1498 width would letterbox the wreath into a tiny middle strip.
    sips -c 704 1040 "$TMP/${name}_norm.png" --out "$TMP/${name}_crop.png" >/dev/null
    sips -p 1040 1040 --padColor "$bg" "$TMP/${name}_crop.png" --out "$TMP/${name}_sq.png" >/dev/null
  fi

  # Full framed icon at splash/preview size for in-app use.
  sips -z 256 256 -s format png "$TMP/${name}_sq.png" --out "$DRAW/splash_${name}.png" >/dev/null
  # NOTE: adaptive-icon backgrounds (ic_<name>_full) are generated by
  # scripts/gen-launcher-icons.py (needs precise scale + shift), and emblems by
  # scripts/gen-emblems.py (PIL colour-key). Do NOT emit those here.
done

# Normalize every output to genuine PNG encoding. sips can leave JPEG bytes in a
# .png-named file when the source was a jpg; aapt's PNG cruncher would then fail.
for f in "$DRAW"/splash_*.png; do
  sips -s format png "$f" --out "$TMP/reenc.png" >/dev/null 2>&1
  mv "$TMP/reenc.png" "$f"
done

echo "Done. Generated:"
ls -1 "$DRAW"/splash_*.png
